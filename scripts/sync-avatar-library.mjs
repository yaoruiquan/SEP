import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkgRoot = resolve(root, 'web/node_modules/@dicebear/styles');
const pkg = JSON.parse(readFileSync(resolve(pkgRoot, 'package.json'), 'utf8'));
const catalogPath = resolve(root, 'backend/src/shared/dicebear-catalog.json');
const previous = JSON.parse(readFileSync(catalogPath, 'utf8'));
const previousById = new Map(previous.map((style) => [style.id, style]));
const catalog = Object.entries(pkg.exports).map(([key, entry]) => {
  const id = key.slice(2, -5);
  const definition = JSON.parse(readFileSync(resolve(pkgRoot, entry.default), 'utf8'));
  const meta = definition.meta;
  const old = previousById.get(id);
  return {
    id, name: old?.name ?? id.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join(' '),
    description: old?.description ?? `${meta.creator.name} 设计的头像风格`,
    category: old?.category ?? 'abstract', recommended: old?.recommended ?? false,
    license: { name: meta.license.name, url: meta.license.url,
      attribution: meta.license.text ?? `${meta.creator.name} / ${meta.license.name}`,
      requiresAttribution: ['CC BY 4.0', 'MIT'].includes(meta.license.name) },
  };
}).sort((a, b) => previous.findIndex((style) => style.id === a.id) - previous.findIndex((style) => style.id === b.id));
const imports = catalog.map(({ id }) => `  '${id}': () => import('@dicebear/styles/${id}.json'),`).join('\n');
const files = new Map([
  [catalogPath, `${JSON.stringify(catalog, null, 2)}\n`],
  [resolve(root, 'web/src/features/avatar-library/dicebear-definitions.ts'),
    `// Generated by scripts/sync-avatar-library.mjs from @dicebear/styles ${pkg.version}.\n// Explicit imports keep all styles in the server bundle without runtime network access.\nexport const dicebearDefinitions = {\n${imports}\n};\n`],
  [resolve(root, 'web/public/assets/avatar-libraries/DICEBEAR-LICENSES.txt'),
    readFileSync(resolve(pkgRoot, 'LICENSE.md'), 'utf8')],
  [resolve(root, 'web/public/assets/avatar-libraries/BEANHEADS-LICENSE.txt'),
    readFileSync(resolve(root, 'web/node_modules/beanheads/LICENSE'), 'utf8')],
]);
for (const [path, content] of files) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== content) throw new Error(`Avatar library catalog is stale: ${path}`);
  } else writeFileSync(path, content);
}
console.log(`Verified ${catalog.length} DiceBear styles (${pkg.version}).`);
const robots = JSON.parse(readFileSync(resolve(root, 'backend/src/shared/robohash-assets.json'), 'utf8'));
for (const asset of Object.values(robots).flat()) {
  const png = readFileSync(resolve(root, 'web/public', asset.portraitUrl.slice(1)));
  if (createHash('sha256').update(png).digest('hex').slice(0, 16) !== asset.version) {
    throw new Error(`Robot asset content changed: ${asset.id}`);
  }
}
console.log(`Verified ${Object.values(robots).flat().length} local RoboHash images and Bean Heads license.`);

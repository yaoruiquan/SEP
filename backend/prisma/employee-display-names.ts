const historicalNames = new Map(
  Object.entries(EMPLOYEE_DISPLAY_NAMES).map(([before, after]) => [after, before]),
);

export function historicalEmployeeName(name: string): string {
  return historicalNames.get(name) ?? name;
}

export function employeeDisplayName(name: string): string {
  return Object.prototype.hasOwnProperty.call(EMPLOYEE_DISPLAY_NAMES, name)
    ? EMPLOYEE_DISPLAY_NAMES[name] : name;
}

export function employeeNameAliases(name: string): string[] {
  const historical = historicalEmployeeName(name);
  return [...new Set([historical, employeeDisplayName(historical)])];
}

type EmployeeIdentity = { id: string; name: string; status: string };
export type EmployeeNameChange = { id: string; before: string; after: string };

export function planEmployeeDisplayNames(employees: EmployeeIdentity[]): EmployeeNameChange[] {
  const changes = employees.filter(employee => employee.status === 'APPROVED')
    .flatMap(employee => {
      const after = employeeDisplayName(employee.name);
      return after === employee.name ? [] : [{ id: employee.id, before: employee.name, after }];
    });
  if (new Set(employees.map(employee => employee.id)).size !== employees.length) {
    throw new Error('员工 ID 重复，不能执行改名');
  }
  for (const change of changes) {
    if (employees.some(employee => employee.id !== change.id &&
      employeeNameAliases(change.before).includes(employee.name))) {
      throw new Error(`员工名称有冲突，须人工确认：${change.before} -> ${change.after}`);
    }
  }
  if (new Set(changes.map(change => change.after)).size !== changes.length) {
    throw new Error('新员工名称重复，不能执行改名');
  }
  return changes;
}
